// Turn the compiled "tags" FASLs of tape 7005017 (SMADIR, DIRECT, ANI) back into
// loadable Lisp. Each is a list of (DEFPROP function |file| AUTOLOAD) forms that
// KEN;LOAD's READ-TAGS loaded, so a function's file was loaded the first time
// the function was called. The forms come from tools/fasl.py's decoding
// (reports/fasl/7005017_<name>.txt).
// Usage: node tools/gen-tags.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

mkdirSync("src/director/tags", { recursive: true });
for (const name of ["smadir", "direct", "ani"]) {
  const dump = readFileSync(`reports/fasl/7005017_${name}.txt`, "utf8").split(/\r?\n/);
  const start = dump.findIndex((l) => l.startsWith("-- Top-level forms evaluated at load time"));
  if (start < 0) throw new Error(`no top-level forms in ${name}`);
  const forms = [];
  for (let i = start + 1; i < dump.length && !dump[i].startsWith("--"); i++) {
    const l = dump[i].trim();
    if (l.startsWith("(")) forms.push(l);
  }
  const header = [
    `;;; KEN;${name.toUpperCase()} FASL, the compiled tags file for ${name === "smadir" ? "Director's basic system" : name === "direct" ? "Director's graphics and movie files" : "Ani"},`,
    ";;; turned back into source from the FASL on tape 7005017 (see reports/fasl/).",
    `;;; ${forms.length} forms, exactly as compiled. Generated by tools/gen-tags.mjs.`,
    "",
  ];
  writeFileSync(`src/director/tags/${name}.lisp`, header.join("\n") + forms.join("\n") + "\n");
  console.log(`${name}: ${forms.length} forms`);
}
